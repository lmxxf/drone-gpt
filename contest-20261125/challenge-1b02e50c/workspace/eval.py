def archive_native_output(run: Path) -> dict:
    """Losslessly archive bytes, without opening NetCDF in GPU worker threads."""
    source = run / 'input.out.nc'
    if not source.is_file():
        raise EvaluatorError('native GX completed without its documented input.out.nc')
    target = run / 'input.out.nc.gz'
    partial = run / 'input.out.nc.gz.partial'
    if target.exists() or partial.exists():
        raise EvaluatorError('native output archive already exists')
    started = time.time()
    source_sha = digest(source)
    source_bytes = source.stat().st_size
    with source.open('rb') as native, partial.open('wb') as packed:
        with gzip.GzipFile(filename='', mode='wb', fileobj=packed,
                           compresslevel=1, mtime=0) as archive:
            while chunk := native.read(1024 * 1024):
                archive.write(chunk)
    restored_sha = hashlib.sha256()
    with gzip.open(partial, 'rb') as archive:
        while chunk := archive.read(1024 * 1024):
            restored_sha.update(chunk)
    if restored_sha.hexdigest() != source_sha:
        raise EvaluatorError('lossless native-output archive changed original bytes')
    partial.replace(target)
    (run / 'native-output.sha256').write_text(source_sha + '\n')
    record = {'native_output_sha256': source_sha, 'native_output_bytes': source_bytes,
              'archive_sha256': digest(target), 'archive_bytes': target.stat().st_size,
              'archive_seconds': time.time() - started, 'archive_format': 'gzip-lossless'}
    source.unlink()
    return record


def native_output_path(run: Path, case: dict) -> Path:
    name = 'input.out.nc.gz' if case['gx'].get('archive_native_output') == 'gzip-lossless' else 'input.out.nc'
    return run / name


def read_flux(path: Path, geometry: dict, field_scale: float, case: dict):
    if path.suffix == '.gz':
        # Restore the exact native bytes; only the main-thread collector opens
        # NetCDF. The archived original SHA is checked before measurements.
        expected = (path.parent / 'native-output.sha256').read_text().strip()
        with tempfile.TemporaryDirectory(prefix='native-read-', dir=path.parent) as folder:
            restored = Path(folder) / 'input.out.nc'
            with gzip.open(path, 'rb') as source, restored.open('wb') as target:
                while chunk := source.read(1024 * 1024):
                    target.write(chunk)
            if digest(restored) != expected:
                raise EvaluatorError('lossless native-output archive failed SHA-256 verification')
            return read_flux(restored, geometry, field_scale, case)
    from netCDF4 import Dataset
    with Dataset(path) as d:
        values = [d.groups[group].variables[name][:] for group, name in (
            ('Grids', 'time'), ('Diagnostics', 'HeatFlux_st'),
            ('Geometry', 'grho'), ('Geometry', 'jacobian'))]
        if any(np.ma.getmaskarray(value).any() for value in values):
            raise Unresolved('missing native heat-flux or geometry samples')
        time_native, flux, grho, jac = [np.asarray(value, dtype=float) for value in values]
    if flux.shape != (len(time_native), 1):
        raise EvaluatorError('unexpected native GX HeatFlux_st layout')
    if any(not np.isfinite(x).all() for x in (time_native, flux, grho, jac)):
        raise Unresolved('nonfinite native heat-flux output')
    if len(time_native) < 3 or np.any(np.diff(time_native) <= 0) or np.any(jac <= 0) or np.any(grho <= 0):
        raise Unresolved('invalid time or native geometry weights')
    gradient_average = float(np.sum(jac * grho) / np.sum(jac))
    a, B = case['fixed']['minor_radius_m'], case['fixed']['axis_B00_T']
    L = geometry['L_native_m']
    B_native = geometry['B_native_unscaled_T'] * field_scale
    # Recover radial-coordinate flux in x_common=a*sqrt(s), then convert its
    # gyro-Bohm unit: QGB_native/QGB_common=(B/B_native)^2*(a/L)^2.
    factor = gradient_average * (B / B_native)**2 * (a / L)**3
    time_common, flux_common = time_native * L / a, flux[:, 0] * factor
    if not np.isfinite(time_common).all() or not np.isfinite(flux_common).all():
        raise Unresolved('nonfinite heat flux after common-unit conversion')
    return time_common, flux_common, {
        'native_output_sha256': digest(path), 'gradient_average': gradient_average,
        'B_native_physical_T': B_native, 'common_flux_factor': factor}


def correlation_time(values: np.ndarray, dt: float) -> float:
    y = values - values.mean()
    if np.dot(y, y) == 0:
        return 0.0
    n = len(y)
    ft = np.fft.rfft(y, n=2*n)
    ac = np.fft.irfft(ft * ft.conj(), n=2*n)[:n] / np.arange(n, 0, -1)
    ac /= ac[0]
    # Initial positive paired sequence, stopping before an unsupported tail.
    total = 0.0
    for j in range(1, n-1, 2):
        pair = ac[j] + ac[j+1]
        if pair <= 0:
            break
        total += pair
    return dt * (0.5 + total)


def block_means(times: np.ndarray, flux: np.ndarray, case: dict):
    gx, stats = case['gx'], case['statistics']
    start, end = gx['tau_discard'], gx['tau_end']
    if times[0] > start or times[-1] < end:
        raise Unresolved('native run does not cover the complete fixed statistical window')
    edges = np.linspace(start, end, stats['blocks_per_run'] + 1)
    means = []
    for lo, hi in zip(edges[:-1], edges[1:]):
        mask = (times > lo) & (times < hi)
        x = np.concatenate(([lo], times[mask], [hi]))
        y = np.interp(x, times, flux)
        means.append(float(np.trapezoid(y, x) / (hi - lo)))
    dt = stats['uniform_sampling_delta_tau']
    sample = np.arange(start, end + dt/2, dt)
    intervals = np.diff(times[(times >= start-dt) & (times <= end+dt)])
    if len(intervals) == 0 or np.max(intervals) > dt * 1.01:
        raise Unresolved('diagnostic cadence too coarse for correlation estimate')
    tau_corr = correlation_time(np.interp(sample, times, flux), dt)
    if (end-start) / stats['blocks_per_run'] < stats['minimum_block_over_correlation_time'] * tau_corr:
        raise Unresolved('tail window too correlated for the fixed block protocol')
    return np.asarray(means), tau_corr


def level_statistics(runs: list[np.ndarray], reference_mean: float, case: dict):
    s = case['statistics']
    blocks = np.concatenate(runs)
    if len(runs) != 2 or any(len(r) != s['blocks_per_run'] for r in runs):
        raise EvaluatorError('missing independent seed or statistical block')
    quantile = float(student_t.ppf(1 - (1-s['joint_confidence']) / (2*s['comparison_family_size']), len(blocks)-1))
    mean = float(blocks.mean())
    half = float(quantile * blocks.std(ddof=1) / math.sqrt(len(blocks)))
    if reference_mean <= 0:
        raise EvaluatorError('reference mean must be positive')
    if half > s['maximum_statistical_halfwidth_over_reference_mean'] * reference_mean:
        raise Unresolved('statistical halfwidth exceeds fixed reference tolerance')
    # Check each seed's halves separately: opposite drifts must not cancel
    # after pooling. This is a finite-window consistency screen, not proof of
    # a stationary process or of the stated interval's frequentist coverage.
    groups = [(runs[0], runs[1])] + [(r[:len(r)//2], r[len(r)//2:]) for r in runs]
    for left, right in groups:
        allowance = quantile * math.sqrt(float(left.var(ddof=1)/len(left) + right.var(ddof=1)/len(right)))
        allowance += s['stationarity_relative_tolerance'] * reference_mean
        if abs(float(left.mean()-right.mean())) > allowance:
            raise Unresolved('independent seeds or tail halves are not statistically stationary')
    return {'mean': mean, 'statistical_halfwidth': half, 'block_means': blocks.tolist()}


def run_gx_jobs(jobs: list[dict], devices: list[str], case: dict, deadline: float):
    """Run independent native inputs; read NetCDF only in the calling thread."""
    if not devices or any(not value or value.strip() != value for value in devices):
        raise EvaluatorError('GX requires explicit, nonempty CUDA device selectors')
    canonical = [str(int(value)) if value.isdecimal() else value.lower() for value in devices]
    if len(set(canonical)) != len(canonical):
        raise EvaluatorError('GX worker device selectors must be distinct')
    cancelled = threading.Event()
    pending = Queue()
    for job in jobs:
        pending.put(job)

    def run_batch(device):
        while True:
            if cancelled.is_set():
                return
            try:
                job = pending.get_nowait()
            except Empty:
                return
            run = job['path']
            remaining = min(case['gx']['per_run_budget_sec'], deadline-time.time())
            if remaining <= 0:
                raise Unresolved('whole native evaluation budget exceeded')
            started = time.time()
            env = os.environ.copy()
            env['CUDA_VISIBLE_DEVICES'] = device
            with (run/'gx.log').open('wb') as log:
                process = subprocess.Popen([case['gx']['executable'], 'input.in'], cwd=run,
                                           env=env, stdout=log, stderr=subprocess.STDOUT)
                try:
                    while process.poll() is None:
                        if cancelled.is_set():
                            return
                        left = remaining-(time.time()-started)
                        if left <= 0:
                            raise Unresolved(f"GX time limit at {job['point']} {run.name}")
                        try:
                            process.wait(timeout=min(1.0, left))
                        except subprocess.TimeoutExpired:
                            continue
                    if process.returncode != 0:
                        raise Unresolved(f"GX exit {process.returncode} at {job['point']} {run.name}; see gx.log")
                finally:
                    if process.poll() is None:
                        process.terminate()
                        try:
                            process.wait(timeout=5)
                        except subprocess.TimeoutExpired:
                            process.kill()
                            process.wait()
            job.update(seconds=time.time()-started, cuda_device=device)
            archive_record = {}
            if case['gx'].get('archive_native_output') == 'gzip-lossless':
                archive_record = archive_native_output(run)
            (run/'native-run.json').write_text(json.dumps({
                'point':job['point'], 'level':job['level'], 'seed':job['seed'],
                'seconds':job['seconds'], 'cuda_device':device,
                'input_sha256':digest(run/'input.in'), 'exit_code':process.returncode,
                **archive_record,
            }, indent=2)+'\n')

    with ThreadPoolExecutor(max_workers=len(devices)) as pool:
        futures = [pool.submit(run_batch, device) for device in devices]
        try:
            for future in as_completed(futures):
                future.result()
        except BaseException:
            cancelled.set()
            raise


def thermal_stage(wout: Path, work: Path, magnetic: dict, case: dict, baseline: dict,
                  deadline: float, devices: list[str]):
    result, prepared, geometries = {}, [], {}
    field_scale = magnetic['stages']['alpha']['field_scale']
    # Geometry and all HDF5/NetCDF operations stay in one thread. Native GX
    # processes have separate working directories and one assigned GPU each.
    for point in case['points']:
        folder = work / point['id']
        folder.mkdir(parents=True)
        geometry = geometry_stage(wout, folder/'eik.nc', point, case)
        geometries[point['id']] = geometry
        for level in case['gx']['levels']:
            for seed in case['gx']['seeds']:
                run = folder / f"{level['id']}-{seed}"
                run.mkdir()
                (run/'eik.nc').write_bytes((folder/'eik.nc').read_bytes())
                (run/'input.in').write_text(gx_input(point, level, seed, geometry, field_scale, case))
                prepared.append({'point':point['id'], 'level':level['id'], 'seed':seed, 'path':run})
    run_gx_jobs(prepared, devices, case, deadline)
    measured = {(job['point'], job['level'], job['seed']):job for job in prepared}
    for point in case['points']:
        folder = work / point['id']
        geometry = geometries[point['id']]
        summaries, records = {}, []
        for level in case['gx']['levels']:
            runs = []
            for seed in case['gx']['seeds']:
                job = measured[point['id'], level['id'], seed]
                run = job['path']
                output = native_output_path(run, case)
                if not output.is_file():
                    raise EvaluatorError(f'native GX output is missing: {output.name}')
                times, flux, normalization = read_flux(output, geometry, field_scale, case)
                blocks, corr = block_means(times, flux, case)
                runs.append(blocks)
                record = {'level':level['id'], 'seed':seed, 'correlation_time':corr,
                          'seconds':job['seconds'], 'cuda_device':job['cuda_device'],
                          'input_sha256':digest(run/'input.in'),
                          'block_means':blocks.tolist(), **normalization}
                records.append(record)
                # Preserve completed native measurements even if a later point
                # cannot resolve. This record never upgrades a failed score.
                (run/'measurement.json').write_text(json.dumps(record, indent=2, allow_nan=False)+'\n')
            summaries[level['id']] = level_statistics(runs, baseline['points'][point['id']]['mean'], case)
            (folder/f"{level['id']}-statistics.json").write_text(
                json.dumps(summaries[level['id']], indent=2, allow_nan=False)+'\n')
        coarse, fine = summaries['coarse'], summaries['fine']
        delta = abs(fine['mean']-coarse['mean'])
        reference_mean = baseline['points'][point['id']]['mean']
        if delta > case['statistics']['maximum_resolution_difference_over_reference_mean'] * reference_mean:
            raise Unresolved(f"{point['id']}: perpendicular resolution difference too large")
        half = fine['statistical_halfwidth'] + coarse['statistical_halfwidth'] + delta
        result[point['id']] = {'mean':fine['mean'], 'upper':fine['mean']+half,
                              'lower':fine['mean']-half, 'resolution_difference':delta,
                              'levels':summaries, 'geometry':geometry, 'runs':records}
        (folder/'point.json').write_text(json.dumps(result[point['id']], indent=2, allow_nan=False)+'\n')
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('submission', type=Path)
    parser.add_argument('--workdir', type=Path, required=True)
    parser.add_argument('--reward-dir', type=Path, default=Path('/logs/verifier'))
    parser.add_argument('--threads', type=int, default=64)
    parser.add_argument('--gx-gpus', help='comma-separated CUDA device selectors; default uses the declared GPU count')
    args = parser.parse_args()
    args.reward_dir.mkdir(parents=True, exist_ok=True)
    started = time.time()
    details = {'status':None}
    reward = {'reward':0.0, 'valid':0, 'feasible':0, 'evaluator_error':0}
    try:
        root = Path(__file__).resolve().parent
        case, baseline = load_configuration(root)
        devices = (args.gx_gpus.split(',') if args.gx_gpus is not None else
                   [str(i) for i in range(case['budget']['gpus'])])
        details['gx_cuda_devices'] = devices
        details['case_sha256'] = digest(root/'case.json')
        if args.workdir.exists() and any(args.workdir.iterdir()):
            raise EvaluatorError('physics workdir must be empty; stale output is not reusable')
        args.workdir.mkdir(parents=True, exist_ok=True)
        snapshot = args.workdir/'submission.json'
        submission_snapshot(args.submission, snapshot, case)
        details['submission_sha256'] = digest(snapshot)
        mod = load_magnetics(root, case)
        deadline = started + case['budget']['whole_evaluation_sec']
        magnetic_work = args.workdir/'magnetic'
        magnetic_work.mkdir()
        metrics, magnetic, wout, nfp = magnetic_stage(snapshot, magnetic_work, case, mod, args.threads, deadline)
        v = violations(metrics, case['constraints'])
        details.update(metrics=metrics, violations=v, magnetic=magnetic, nfp=nfp)
        if any(x > 0 for x in v.values()):
            reward.update(reward=infeasible_score(v), valid=1)
            details.update(status='ok', feasible=False, heat_flux='not run: magnetic or volume constraints failed')
        else:
            points = thermal_stage(wout, args.workdir/'gx', magnetic, case, baseline, deadline, devices)
            J = objective(points, baseline['points'], [p['id'] for p in case['points']])
            value = feasible_score(J, baseline['J_reference'])
            reward.update(reward=value, valid=1, feasible=1)
            details.update(status='ok', feasible=True, points=points, J=J,
                           J_reference=baseline['J_reference'], all_points_improved=J<1)
    except InvalidSubmission as exc:
        details.update(status='invalid_submission', reason=str(exc))
    except Unresolved as exc:
        details.update(status='candidate_unresolved', reason=str(exc))
    except Exception as exc:
        reward['evaluator_error'] = 1
        details.update(status='evaluator_error', reason=f'{type(exc).__name__}: {exc}', traceback=traceback.format_exc())
    details['seconds'] = time.time()-started
    (args.reward_dir/'details.json').write_text(json.dumps(details, indent=2, allow_nan=False, default=str)+'\n')
    (args.reward_dir/'reward.json').write_text(json.dumps(reward, allow_nan=False)+'\n')
    print(json.dumps(reward))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
