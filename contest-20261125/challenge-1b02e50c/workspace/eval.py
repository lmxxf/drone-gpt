class InvalidSubmission(Exception):
    pass


class Unresolved(Exception):
    pass


class EvaluatorError(Exception):
    pass


def digest(path: Path) -> str:
    with path.open('rb') as f:
        return hashlib.file_digest(f, 'sha256').hexdigest()


def unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f'duplicate JSON key: {key}')
        result[key] = value
    return result


def read_json(path: Path):
    return json.loads(path.read_text(), object_pairs_hook=unique_object)


def number(value, name: str) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise EvaluatorError(f'{name} must be a finite number')
    result = float(value)
    if not math.isfinite(result):
        raise EvaluatorError(f'{name} must be a finite number')
    return result


def violations(metrics: dict, constraints: dict) -> dict:
    result = {}
    for key, spec in constraints.items():
        value = number(metrics[key], key)
        threshold = number(spec['threshold'], key + '.threshold')
        scale = number(spec['progress_scale'], key + '.progress_scale')
        if scale <= 0:
            raise EvaluatorError(f'{key}: nonpositive violation scale')
        if spec['sense'] == 'upper':
            delta = value - threshold
        elif spec['sense'] == 'lower':
            delta = threshold - value
        else:
            raise EvaluatorError(f'{key}: unknown constraint direction')
        result[key] = max(0.0, delta / scale)
    return result


def infeasible_score(v: dict) -> float:
    if not any(x > 0 for x in v.values()):
        raise EvaluatorError('infeasible score requested for a feasible design')
    value = 0.5 * math.exp(-sum(x * x for x in v.values()))
    return min(value, math.nextafter(0.5, 0.0))


def objective(points: dict, baseline: dict, ids: list[str]) -> float:
    if set(points) != set(ids) or set(baseline) != set(ids):
        raise EvaluatorError('missing or unexpected heat-flux point')
    ratios = []
    for key in ids:
        lower = number(baseline[key]['lower'], key + '.reference_lower')
        upper = number(points[key]['upper'], key + '.candidate_upper')
        if lower <= 0:
            raise EvaluatorError(f'{key}: reference lower bound must be positive')
        ratios.append(upper / lower)
    return max(ratios)


def feasible_score(J: float, J_reference: float) -> float:
    # expit is stable for arbitrarily large finite J. Do not clip signed flux.
    return float(0.5 + 0.5 * expit(J_reference - J))


def load_configuration(root: Path):
    case = read_json(root / 'case.json')
    if case['schema'] != 'fusionx-d0/v0.1':
        raise EvaluatorError('unsupported case schema')
    lock_path = root / case['runtime_lock']
    lock = read_json(lock_path)
    if lock['state'] != 'verified':
        raise EvaluatorError('D0 runtime has not passed fresh native image and isolation checks')
    if lock['GX_commit'] != case['gx']['commit'] or lock['gx_geometry_commit'] != case['gx']['geometry_commit']:
        raise EvaluatorError('runtime source versions disagree with case')
    if not isinstance(lock['image_digest'], str) or '@sha256:' not in lock['image_digest']:
        raise EvaluatorError('runtime requires a verified image digest')
    if lock['isolation'] != 'clean_trusted_verifier':
        raise EvaluatorError('trusted verifier isolation has not been verified')
    files = lock['verified_files']
    required = {'/opt/stellarator/bin/xvmec2000', '/opt/stellarator/bin/xneo',
                '/opt/stellarator/bin/simple.x', case['gx']['executable'], sys.executable}
    if not required.issubset({item['path'] for item in files}):
        raise EvaluatorError('runtime lock does not cover required native executables and Python')
    for item in files:
        if digest(Path(item['path'])) != item['sha256']:
            raise EvaluatorError(f"runtime file changed: {item['path']}")
    baseline = read_json(root / case['reference']['baseline'])
    if baseline['state'] != 'calibrated':
        raise EvaluatorError('reference GX heat flux and convergence have not been calibrated')
    if baseline['case_sha256'] != digest(root / 'case.json'):
        raise EvaluatorError('reference was computed for a different case')
    if baseline['boundary_sha256'] != case['reference']['boundary_sha256']:
        raise EvaluatorError('reference boundary identity changed')
    if baseline['runtime_lock_sha256'] != digest(lock_path):
        raise EvaluatorError('reference runtime identity changed')
    ids = [p['id'] for p in case['points']]
    reference_J = objective(baseline['points'], baseline['points'], ids)
    if not math.isclose(reference_J, number(baseline['J_reference'], 'J_reference'), rel_tol=1e-12):
        raise EvaluatorError('reference objective does not match recorded intervals')
    if baseline.get('evidence_schema') != 'fusionx-d0-evidence/v2':
        raise EvaluatorError('unsupported reference evidence schema')
    assessments = {
        'zero_drive': {'expected_limit_recovered'},
        'parallel_resolution': {'adequate_for_declared_scope'},
        'velocity_resolution': {'adequate_for_declared_scope'},
        'box_size': {'adequate_for_declared_scope'},
        'tube_length': {'definition_verified', 'sensitivity_measured'},
        'parallel_boundary': {'definition_verified', 'sensitivity_measured'},
        'native_solver_benchmark': {'comparison_met', 'documented_historical_discrepancy'},
        'reference_replay': {'replay_verified'},
        'runtime_isolation': {'isolation_verified'},
    }
    evidence = baseline.get('evidence')
    if not isinstance(evidence, dict):
        raise EvaluatorError('reference evidence records are missing')
    for name, accepted in assessments.items():
        record = evidence.get(name)
        if not isinstance(record, dict):
            raise EvaluatorError(f'reference lacks {name} evidence')
        if not isinstance(record.get('assessment'), str) or record['assessment'] not in accepted:
            raise EvaluatorError(f'reference {name} assessment is not sufficient for its declared scope')
        for field in ('scope', 'finding'):
            if not isinstance(record.get(field), str) or not record[field].strip():
                raise EvaluatorError(f'reference {name} lacks a nonempty {field}')
        if not isinstance(record.get('artifacts'), list) or not record['artifacts']:
            raise EvaluatorError(f'no native evidence artifacts: {name}')
        if name == 'native_solver_benchmark':
            if record['assessment'] == 'comparison_met':
                if record.get('upstream_result') != 'passed':
                    raise EvaluatorError('benchmark comparison_met requires the original comparison to pass')
            else:
                if record.get('upstream_result') != 'failed' or record['scope'] != 'fixed_native_discrete_protocol':
                    raise EvaluatorError('historical benchmark discrepancy must retain failure and fixed-protocol scope')
                roles = {item['role'] for item in record['artifacts']
                         if isinstance(item, dict) and isinstance(item.get('role'), str)}
                if not {'original_thresholds', 'measured_difference', 'discrepancy_analysis'}.issubset(roles):
                    raise EvaluatorError('historical benchmark discrepancy lacks original thresholds, measurements or analysis')
        for artifact in record['artifacts']:
            if not isinstance(artifact, dict) or any(
                    not isinstance(artifact.get(field), str) or not artifact[field].strip()
                    for field in ('path', 'sha256')):
                raise EvaluatorError(f'incomplete calibration artifact identity: {name}')
            if digest(root / artifact['path']) != artifact['sha256']:
                raise EvaluatorError(f'calibration artifact changed: {name}')
    return case, baseline


def load_magnetics(root: Path, case: dict):
    path = root / 'magnetic_eval.py'
    if digest(path) != case['magnetic']['source_sha256']:
        raise EvaluatorError('A magnetic evaluator source changed')
    name = 'fusionx_d0_magnetic_evaluator'
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod
    spec.loader.exec_module(mod)
    mod.M_MAX = case['submission']['m_max']
    mod.N_MAX = case['submission']['n_max']
    mod.NFP_MAX = case['submission']['nfp']
    mod.VMEC_NS_FINAL = (case['magnetic']['vmec_ns_final'],)
    return mod


def submission_snapshot(submission: Path, destination: Path, case: dict):
    try:
        # Reject FIFOs/devices and links before any blocking read. The fresh
        # verifier receives an ordinary file, not an agent-controlled process.
        fd = os.open(submission, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
        with os.fdopen(fd, 'rb') as f:
            if not stat.S_ISREG(os.fstat(f.fileno()).st_mode):
                raise InvalidSubmission('boundary.json must be a regular file')
            data = f.read(case['submission']['max_bytes'] + 1)
        if len(data) > case['submission']['max_bytes']:
            raise InvalidSubmission('boundary.json exceeds 1 MiB')
        parsed = json.loads(data, object_pairs_hook=unique_object)
        if not isinstance(parsed, dict) or type(parsed.get('nfp')) is not int or parsed['nfp'] != case['submission']['nfp']:
            raise InvalidSubmission('nfp must be the integer 2')
    except (OSError, UnicodeError, ValueError, RecursionError) as exc:
        raise InvalidSubmission(f'unreadable boundary.json: {exc}') from exc
    destination.write_bytes(data)


def magnetic_stage(submission: Path, work: Path, case: dict, mod, threads: int, deadline: float):
    details = {}
    try:
        # Early format checking avoids mistaking input errors for physics failure.
        b = mod.read_boundary(submission)
    except mod.Invalid as exc:
        raise InvalidSubmission(str(exc)) from exc
    try:
        mod.evaluate(submission, work, threads, details,
                     min(deadline, time.time() + case['magnetic']['magnetic_budget_sec']),
                     case['magnetic']['vmec_budget_sec'])
    except mod.Invalid as exc:
        raise Unresolved(str(exc)) from exc
    metrics = dict(details['metrics'])
    metrics['volume_relative_error'] = abs(details['stages']['geometry']['volume'] / case['fixed']['reference_volume_m3'] - 1)
    metrics['f_alpha_upper'] = details['stages']['alpha']['wilson_95'][1]
    if details['stages']['boozer']['e_B'] > case['magnetic']['boozer_valid_error_max']:
        raise Unresolved('Boozer error exceeds D0 validity threshold')
    attempt = details['stages']['vmec']['attempt']
    wout = work / f'vmec_attempt{attempt}' / 'wout_eq.nc'
    # The fixed A interface is checked by its hash; derive the path from its
    # actual run result layout, rather than searching for any old wout.
    if not wout.exists():
        raise EvaluatorError(f'A evaluator output path is missing: {wout}')
    return metrics, details, wout, b.nfp


def geometry_stage(wout: Path, destination: Path, point: dict, case: dict):
    from gx_geometry import create_eik_from_vmec
    from gx_geometry.vmec import Vmec
    from gx_geometry.vmec_diagnostics import vmec_fieldline_from_center

    gx, a = case['gx'], case['fixed']['minor_radius_m']
    vmec = Vmec(str(wout))
    L = number(float(vmec.wout.Aminor_p), 'VMEC Aminor_p')
    if L <= 0:
        raise Unresolved('VMEC reference length is nonpositive')

    def tube_length(turns):
        fl = vmec_fieldline_from_center(vmec, point['s'], point['theta_pest_center'],
                                        point['zeta_center'], turns, 1001)
        return float(np.asarray(fl.length).squeeze())

    wanted = gx['tube_length_over_a'] * a / L
    shortest, longest = tube_length(0.001), tube_length(20.0)
    if not np.isfinite([shortest, longest]).all() or not shortest <= wanted <= longest:
        raise Unresolved('native field line does not bracket the fixed physical tube length')
    turns = brentq(lambda x: tube_length(x) - wanted, 0.001, 20.0, xtol=1e-10)
    fl = create_eik_from_vmec(str(wout), point['s'],
                             theta0=point['theta_pest_center'], zeta0=point['zeta_center'],
                             nz=gx['ntheta'] + 1, poloidal_turns=turns,
                             sigma_Bxy=gx['geometry_sigma_Bxy'], eik_filename=str(destination),
                             Domain={'boundary': gx['boundary']})
    if abs(float(np.asarray(fl.length).squeeze()) / wanted - 1) > gx['geometry_length_tolerance_relative']:
        raise Unresolved('native geometry did not recover fixed physical tube length')
    return {'L_native_m': float(fl.L_reference), 'B_native_unscaled_T': float(fl.B_reference),
            'length_over_a': wanted * L / a, 'poloidal_turns': turns,
            'geometry_sha256': digest(destination)}


