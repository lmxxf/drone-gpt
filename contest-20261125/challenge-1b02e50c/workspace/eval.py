"""D0 native evaluator. No surrogate, cached self-report or physics replacement.

The generated trusted directory contains case.json, runtime-lock.json,
reference/baseline.json and magnetic_eval.py. A complete calibrated runtime is
required. The draft intentionally fails with evaluator_error instead of scoring
an unmeasured reference. Public copies are generated by build_package.py.
"""
